const operationalSites: SiteInfrastructure[] = [];
const targetTotal = 152;
const neededOperational = targetTotal - downtimeSites.length - maintenanceSites.length; // 152 - 8 - 4 = 140

for (let i = 0; i < neededOperational; i++) {
  const muni = operationalMunicipalities[i % operationalMunicipalities.length];
  const cycle = Math.floor(i / operationalMunicipalities.length) + 1;
  const handler = handlers[i % handlers.length];
  
  // Apply a tiny jitter per cycle so multiple facilities in the same town don't perfectly stack
  const jitterLat = (cycle - 1) * 0.015 * (i % 2 === 0 ? 1 : -1);
  const jitterLng = (cycle - 1) * 0.015 * (i % 3 === 0 ? 1 : -1);
  
  operationalSites.push({
    id: `site-op-${String(i + 1).padStart(3, '0')}`,
    name: `DICT ${muni.prov.toUpperCase()} ${muni.name}${cycle > 1 ? ` ${cycle}` : ''}`,
    code: `${muni.code}-${String(cycle).padStart(2, '0')}`,
    region: muni.prov === 'BARMM' || muni.prov === 'Basilan' ? 'BARMM' : 'Region X (Northern Mindanao)',
    province: muni.prov,
    status: 'Operational',
    deviceCount: (i % 5) + 2,
    offlineCount: 0,
    onlineCount: (i % 5) + 2,
    activeAlarmCount: 0,
    lastKnownIp: `10.144.${(i % 120) + 10}.${(i % 250) + 1}`,
    assignedHandler: handler,
    coordinates: {
      lat: muni.lat + jitterLat,
      lng: muni.lng + jitterLng,
    },
  });
}

